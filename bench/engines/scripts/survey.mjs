#!/usr/bin/env node
// Writes bench/engines/survey.json and survey.md from survey-data.json (the researched verdicts,
// with sources) plus what is actually installed under bench/engines (read from disk now: git
// commits and tags of the source checkouts, SHA-256 and --version output of every binary).
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync, spawnSync } from 'node:child_process';
import { ENGINES_DIR } from '../harness/lib.mjs';

const data = JSON.parse(fs.readFileSync(path.join(ENGINES_DIR, 'survey-data.json'), 'utf8'));
const sh = (cmd, args, opts = {}) => { try { return execFileSync(cmd, args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], timeout: 20000, ...opts }).trim(); } catch (e) { return null; } };
const sha = (p) => sh('shasum', ['-a', '256', p])?.split(/\s+/)[0] ?? null;
const RMLX_LIB = `${ENGINES_DIR}/rmlx/deps/mlx-c/lib:${ENGINES_DIR}/rmlx/deps/mlx-wheel/mlx/lib`;

function gitInfo(dir) {
  const d = path.join(ENGINES_DIR, dir);
  if (!fs.existsSync(path.join(d, '.git'))) return null;
  return {
    path: dir, commit: sh('git', ['-C', d, 'rev-parse', 'HEAD']), commit_date: sh('git', ['-C', d, 'log', '-1', '--format=%cI']),
    tags_at_head: sh('git', ['-C', d, 'tag', '--points-at', 'HEAD'])?.split('\n').filter(Boolean) ?? [], remote: sh('git', ['-C', d, 'remote', 'get-url', 'origin']),
    dirty: (sh('git', ['-C', d, 'status', '--porcelain', '--untracked-files=no']) || '') !== '',
  };
}
function binInfo(rel, env = {}) {
  const p = path.join(ENGINES_DIR, rel.replace(/^bench\/engines\//, ''));
  if (!fs.existsSync(p)) return { path: rel, present: false };
  const r = spawnSync(p, ['--version'], { encoding: 'utf8', env: { ...process.env, ...env }, timeout: 20000 });
  const lines = `${r.stdout || ''}\n${r.stderr || ''}`.split('\n').map((l) => l.trim()).filter((l) => /version|\d+\.\d+/i.test(l) && !/ggml_metal|load_backend|inconnu|unknown|error/i.test(l));
  const version = lines.length ? lines.slice(0, 2).join(' | ') : null;
  return { path: rel, present: true, size: fs.statSync(p).size, sha256: sha(p), version_output: version ? version.split('\n')[0].slice(0, 200) : null };
}

const out = { generated: new Date().toISOString(), as_of: data.as_of, model: data.model, requirements: data.requirements, engines: [] };
for (const e of data.engines) {
  const hard = data.requirements.hard.map((k) => e.hard?.[k]?.ok);
  const qualifies = hard.every((v) => v === true);
  const rec = { ...e, qualifies_hard_requirements: qualifies };
  if (e.install) {
    const inst = { ...e.install };
    inst.source = gitInfo(e.install.method === 'source' ? e.install.path.replace(/^bench\/engines\//, '') : (e.install.source_checkout || '').replace(/^bench\/engines\//, ''));
    inst.binaries = (e.install.binaries || []).map((b) => binInfo(b, e.id === 'rmlx' ? { DYLD_LIBRARY_PATH: RMLX_LIB } : {}));
    if (e.install.asset) {
      const dir = path.join(ENGINES_DIR, e.install.path.replace(/^bench\/engines\//, ''));
      const tar = fs.readdirSync(dir).find((f) => f.endsWith('.tar.gz'));
      if (tar) inst.asset_file = { file: path.join(e.install.path, tar), sha256: sha(path.join(dir, tar)) };
    }
    if (e.id === 'rmlx') {
      inst.mlx_wheels = fs.readdirSync(path.join(ENGINES_DIR, 'rmlx/deps/wheels')).map((f) => ({ file: f, sha256: sha(path.join(ENGINES_DIR, 'rmlx/deps/wheels', f)) }));
      inst.mlx_c = gitInfo('rmlx/deps/mlx-c-src');
    }
    if (e.id === 'llamacpp') inst.plugin_vendor_revision = fs.readFileSync(path.join(ENGINES_DIR, '../../plugins/model-llama/vendor/llama.cpp/REVISION'), 'utf8').trim().split('\n');
    rec.installed = inst;
  }
  out.engines.push(rec);
}
fs.writeFileSync(path.join(ENGINES_DIR, 'survey.json'), JSON.stringify(out, null, 1));

// ---- markdown
const yn = (v) => (v === true ? 'yes' : v === false ? 'no' : '?');
let md = `# Inference engine survey for Qwen3.8-27B on Apple Metal (as of ${data.as_of})\n\n`;
md += `Generated by \`node bench/engines/scripts/survey.mjs\` from \`survey-data.json\` plus the installed state on disk (${out.generated}).\n\n`;
md += `**Model.** ${data.model.architecture}\n\n`;
md += `**Hard requirements:** runs the qwen35 hybrid architecture, Metal GPU, about 4-bit weights, streaming, usable from Rust (in-process or a Rust server). Nice to have: ${data.requirements.nice.join(', ')}.\n\n`;
md += `| Engine | Role | Verdict | arch | Metal | 4-bit | stream | Rust | grammar | tools | prefix cache | batching | MTP/spec | KV quant |\n|---|---|---|---|---|---|---|---|---|---|---|---|---|---|\n`;
for (const e of out.engines) {
  const h = e.hard || {}, n = e.nice || {};
  md += `| [${e.name}](${e.repo}) | ${e.role} | **${e.verdict}** | ${yn(h.arch?.ok)} | ${yn(h.metal?.ok)} | ${yn(h.four_bit?.ok)} | ${yn(h.streaming?.ok)} | ${yn(h.rust_usable?.ok)} | ${yn(n.grammar)} | ${yn(n.tool_parse)} | ${yn(n.prefix_cache)} | ${yn(n.batching)} | ${yn(n.spec_mtp)} | ${yn(n.kv_quant)} |\n`;
}
md += `\n## Per engine\n`;
for (const e of out.engines) {
  md += `\n### ${e.name}\n\n- Repo: ${e.repo}\n- Verdict: **${e.verdict}**. ${e.verdict_reason}\n`;
  if (e.owner_claim) md += `- Owner's lead: ${e.owner_claim}. Assessment: ${e.claim_assessment}\n`;
  for (const k of data.requirements.hard) if (e.hard?.[k]) md += `- ${k}: ${yn(e.hard[k].ok)} (${e.hard[k].evidence})\n`;
  if (e.nice_notes) md += `- Features: ${e.nice_notes}\n`;
  if (e.weights) md += `- Weights: ${e.weights}\n`;
  if (e.installed) {
    const i = e.installed;
    md += `- Installed (${i.method}) at \`${i.path}\``;
    if (i.source?.commit) md += `; source commit \`${i.source.commit}\` (${i.source.commit_date}${i.source.tags_at_head.length ? ', tag ' + i.source.tags_at_head.join(',') : ''})`;
    if (i.asset_file) md += `; release asset \`${i.asset_file.file}\` sha256 \`${i.asset_file.sha256}\``;
    md += '\n';
    for (const b of i.binaries) md += `  - \`${b.path}\`: ${b.present ? `sha256 \`${b.sha256}\`${b.version_output ? `, \`${b.version_output}\`` : ''}` : 'missing'}\n`;
    if (i.source_build_blocker) md += `  - Source build blocker on this machine: ${i.source_build_blocker}\n`;
  }
  md += `- Sources: ${e.sources.join(', ')}\n`;
}
fs.writeFileSync(path.join(ENGINES_DIR, 'survey.md'), md);
console.log(`survey: ${out.engines.length} engines, ${out.engines.filter((e) => e.verdict === 'candidate').length} candidates`);

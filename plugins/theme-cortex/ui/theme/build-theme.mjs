// Compiles the theme's sources before Vite bundles them:
//   tokens/cortex.tokens.json -> src/generated/tokens.css (the design's token contexts, both grounds)
//                         -> src/generated/theme-data.ts (tokens, fonts, CodeMirror and xterm themes)
//   @fontsource-variable  -> src/generated/fonts/*.woff2 + src/generated/fonts.css (bundled faces)
// Run from the package folder (`npm run build` does); all paths are relative to it.

import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

const here = import.meta.dirname;

// `--finish` runs after Vite: the faces go next to the stylesheet as files (a library build would
// inline them as data), and their @font-face rules open the stylesheet.
if (process.argv.includes('--finish')) {
  const dist = path.join(here, 'dist');
  fs.cpSync(path.join(here, 'src', 'generated', 'fonts'), path.join(dist, 'fonts'), { recursive: true });
  const faces = fs.readFileSync(path.join(here, 'src', 'generated', 'fonts.css'), 'utf8');
  const style = fs.readFileSync(path.join(dist, 'style.css'), 'utf8');
  fs.writeFileSync(path.join(dist, 'style.css'), `${faces}\n${style}`);
  console.log(`theme fonts: ${fs.readdirSync(path.join(dist, 'fonts')).length} files next to style.css`);
  process.exit(0);
}
const require = createRequire(path.join(here, 'package.json'));
const out = path.join(here, 'src', 'generated');
fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(path.join(out, 'fonts'), { recursive: true });

const tokens = JSON.parse(fs.readFileSync(path.join(here, 'tokens', 'cortex.tokens.json'), 'utf8'));
const GROUND_EXT = 'org.cortexcode.ground';
const plate = {};
const page = {};
for (const [name, token] of Object.entries(tokens.color)) {
  plate[`--${name}`] = token.$value;
  page[`--${name}`] = token.$extensions?.[GROUND_EXT]?.page ?? token.$value;
}
const caret = tokens.other.caret.$value;
const fontStack = (list) => list.map((family) => (/[\s\d]/.test(family) && !family.startsWith('ui-') ? `"${family}"` : family)).join(',');
const fonts = Object.fromEntries(Object.entries(tokens.font).map(([name, token]) => [name, fontStack(token.$value)]));
const decls = (map) => Object.entries(map).map(([name, value]) => `${name}:${value};`).join(' ');

// The five contexts of the design reference, in its order.
const tokensCss = `/* Generated by build-theme.mjs from tokens/cortex.tokens.json. Do not edit. */
:root{
  ${decls(page)}
  --caret:${caret};
  --font-reading:${fonts.reading}; --font-apparatus:${fonts.apparatus}; --font-mono:${fonts.mono};
}
@media (prefers-color-scheme: dark){
  :root:not([data-theme="light"]){
    ${decls(plate)}
  }
}
:root[data-theme="dark"]{
  ${decls(plate)}
}
#cc[data-view="page"]{
  ${decls(page)}
}
#cc[data-view="plate"]{
  ${decls(plate)}
}
`;
fs.writeFileSync(path.join(out, 'tokens.css'), tokensCss);

// Bundled faces: Source Serif 4 (optical size and weight) and Archivo (width and weight), every
// subset, named exactly as the design names them.
const faces = [];
for (const [pkg, file, family] of [
  ['@fontsource-variable/source-serif-4', 'opsz.css', 'Source Serif 4'],
  ['@fontsource-variable/source-serif-4', 'opsz-italic.css', 'Source Serif 4'],
  ['@fontsource-variable/archivo', 'wdth.css', 'Archivo'],
  ['@fontsource-variable/archivo', 'wdth-italic.css', 'Archivo'],
]) {
  const dir = path.dirname(require.resolve(`${pkg}/package.json`));
  const css = fs.readFileSync(path.join(dir, file), 'utf8');
  for (const block of css.split('@font-face').slice(1)) {
    const src = /url\(\.\/files\/([^)]+)\)/.exec(block)?.[1];
    if (!src) continue;
    fs.copyFileSync(path.join(dir, 'files', src), path.join(out, 'fonts', src));
    faces.push('@font-face ' + block.trim()
      .replace(/font-family: '[^']+';/, `font-family: '${family}';`)
      .replace(/font-display: swap;/, 'font-display: block;')
      .replace(/url\(\.\/files\//, 'url(./fonts/'));
  }
}
fs.writeFileSync(path.join(out, 'fonts.css'), `/* Generated by build-theme.mjs: the design's two faces, bundled for offline use. */\n${faces.join('\n\n')}\n`);

// What non-CSS renderers need. Values use the tokens' CSS variables where the renderer takes CSS;
// xterm takes colours, so it gets each ground's resolved values.

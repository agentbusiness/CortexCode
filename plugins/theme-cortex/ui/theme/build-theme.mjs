      '.cm-activeLine': { backgroundColor: 'var(--rubric-wash)' },
      '.cm-activeLineGutter': { backgroundColor: 'transparent', color: 'var(--ink)' },
      '&.cm-focused > .cm-scroller > .cm-selectionLayer .cm-selectionBackground, .cm-selectionBackground, ::selection': { backgroundColor: 'color-mix(in srgb, var(--rubric) 24%, transparent)' },
      '.cm-matchingBracket': { backgroundColor: 'transparent', outline: '1px solid var(--rule-2)' },

// Builds the workbench renderer (ui/renderer -> ui/renderer/dist) and its shared vendor modules
// (react, react-dom, react/jsx-runtime, @cortex/sdk -> ui/renderer/dist/vendor/), which plugins
// reach through the import map instead of bundling their own copies.

import { build } from 'vite';
import react from '@vitejs/plugin-react';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import fs from 'node:fs/promises';
import path from 'node:path';
import { EXTERNALS, RENDERER_DIR, RENDERER_DIST, SHARED_MODULES, UI_BASE, UI_DIR, importMap } from './shared.mjs';

const require = createRequire(import.meta.url);

/** Inject the import map first in <head>, and a CSP that admits exactly that inline script. */
function importMapPlugin() {
  const json = JSON.stringify(importMap());
  const hash = createHash('sha256').update(json).digest('base64');
  const csp = [
    "default-src 'self'",
    `script-src 'self' 'sha256-${hash}'`,
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' data: blob: https://avatars.githubusercontent.com",
    "font-src 'self'",
    "connect-src 'self'",
    "object-src 'none'",
    "base-uri 'none'",
    "frame-src 'none'",
  ].join('; ');
  return {
    name: 'cortex-import-map',
    transformIndexHtml: {
      order: 'pre',
      handler() {
        return [
          { tag: 'meta', attrs: { 'http-equiv': 'Content-Security-Policy', content: csp }, injectTo: 'head-prepend' },
          { tag: 'script', attrs: { type: 'importmap' }, children: json, injectTo: 'head-prepend' },
        ];
      },
    },
  };
}

export async function buildRenderer({ quiet = false } = {}) {
  await build({
    configFile: false,
    root: RENDERER_DIR,
    base: UI_BASE,
    logLevel: quiet ? 'warn' : 'info',
    plugins: [react(), importMapPlugin()],
    build: {
      outDir: RENDERER_DIST,
      emptyOutDir: true,
      target: 'es2023',
      sourcemap: true,
      assetsInlineLimit: 0,
      rolldownOptions: { external: EXTERNALS },
    },
  });
  await buildVendor({ quiet });
}

/**
 * One bundle holds React, ReactDOM and the JSX runtime together (so there is exactly one React),
 * and a thin facade per specifier re-exports its part. The facades' export names are read from the
 * modules themselves, so they match whatever this React version exports.
 */
async function buildVendor({ quiet }) {
  const vendorDir = path.join(RENDERER_DIST, 'vendor');
  const work = path.join(UI_DIR, 'node_modules', '.cache', 'cortex-vendor');
  await fs.mkdir(work, { recursive: true });
  const entry = path.join(work, 'shared-entry.js');
  await fs.writeFile(entry, [
    "import React from 'react';",
    "import ReactDOM from 'react-dom';",
    "import ReactDOMClient from 'react-dom/client';",
    "import JSXRuntime from 'react/jsx-runtime';",
    'export { React, ReactDOM, ReactDOMClient, JSXRuntime };',
    '',
  ].join('\n'));
  await build({
    configFile: false,
    root: UI_DIR,
    logLevel: quiet ? 'warn' : 'info',
    define: { 'process.env.NODE_ENV': JSON.stringify('production') },
    build: {
      outDir: vendorDir,
      emptyOutDir: false,
      target: 'es2023',
      minify: true,
      lib: { entry, formats: ['es'], fileName: () => 'react-shared.js' },
    },
  });

  const previous = process.env.NODE_ENV;
  process.env.NODE_ENV = 'production';
  const facades = {
    react: ['React', require('react')],
    'react/jsx-runtime': ['JSXRuntime', require('react/jsx-runtime')],
    'react-dom': ['ReactDOM', require('react-dom')],
    'react-dom/client': ['ReactDOMClient', require('react-dom/client')],
  };
  if (previous === undefined) delete process.env.NODE_ENV;
  else process.env.NODE_ENV = previous;
  for (const [specifier, [binding, module]] of Object.entries(facades)) {
    const names = Object.keys(module).filter((name) => /^[A-Za-z_$][\w$]*$/.test(name) && name !== 'default');
    const source = [
      `// Facade of ${specifier} over the one shared React bundle (generated by ui/scripts/build-renderer.mjs).`,
      `import { ${binding} as M } from './react-shared.js';`,
      'export default M;',
      `export const { ${names.join(', ')} } = M;`,
      '',
    ].join('\n');
    await fs.writeFile(path.join(vendorDir, SHARED_MODULES[specifier]), source);
  }

  // The SDK is its own package, built on its own; the renderer serves that build.
  const sdkDist = path.join(UI_DIR, 'sdk', 'dist');
  for (const file of ['cortex-sdk.js', 'cortex-sdk.js.map']) {
    await fs.copyFile(path.join(sdkDist, file), path.join(vendorDir, file === 'cortex-sdk.js' ? SHARED_MODULES['@cortex/sdk'] : `${SHARED_MODULES['@cortex/sdk']}.map`));
  }
}

if (import.meta.url === `file://${process.argv[1]}`) {
  buildRenderer().catch((error) => {
    console.error(error);
    process.exit(1);
  });
}

// Writes the "Slot contract" section of every UI plugin package's README from its source: the
// slot it fills, the props its host gives it, the slots it hosts, the workbench state it reads and
// writes, the frame methods it calls and the topics it follows. Run after changing a plugin:
//
//   node scripts/readme-contracts.mjs          (rewrites the sections)
//   node scripts/readme-contracts.mjs --check  (fails when a README is out of date)

import fs from 'node:fs';
import path from 'node:path';
import { uiPackages } from './packages.mjs';

const START = '<!-- slot-contract:start (generated by ui/scripts/readme-contracts.mjs) -->';
const END = '<!-- slot-contract:end -->';

/** Props a host passes to the plugins of a slot (the hosts' own sources say so). */
const PROPS = {
  'settings.host@1': '`{ onClose(): void }` (the card host closes the window with it)',
  'code.editor@1': '`{ active: boolean }` (whether the code view is the pane on screen)',
  'pane.*@1': '`{ active: boolean }` (whether this view is the right pane\'s open tab)',
};

/** Hosts that discover their contributors from the frame's UI plugin list, by slot family (keyed
 * by the host's slot, or by its plugin id where its slot is a shared list such as the band). */
const DISCOVERS = {
  'workbench.rightPane@1': 'every `pane.<name>@1` plugin, as a tab',
  'card-host.card': 'every `card.<name>@1` plugin, as a card section; `settings.host@1` when settings open',
  'settings.host@1': 'every `settings.<name>@1` plugin, as a panel',
};

/** What the SDK's helpers read and write on a plugin's behalf, and the calls and topics they use. */
const HELPERS = {
  useSelection: { reads: ['projectId', 'sessionId'], writes: ['projectId', 'sessionId'] },
  useCodeTarget: { reads: ['code.target', 'projectId'], writes: ['code.target'] },
  useCodeScope: { reads: ['code.scope'], writes: ['code.scope'] },
  useCodeBase: { reads: ['code.base'], writes: ['code.base'] },
  useCodeOpen: { reads: ['code.open'], writes: ['code.open'] },
  useCodeOptions: { reads: ['code.options'], writes: ['code.options'] },
  useCodeDiff: { reads: ['code.target', 'code.scope', 'code.base', 'sessionId'], calls: ['vcs.diff'], topics: ['vcs.changed', 'tools.files_changed'] },
  openInCode: { writes: ['code.open', 'pane.tab'] },
  showPane: { writes: ['pane.tab'] },
  currentPane: { reads: ['pane.tab'] },
  openTarget: { writes: ['projectId', 'sessionId', 'pane.tab', 'chat.focus', 'composer.focus', 'board.view', 'board.focus', 'settings.open'] },
  useProjects: { calls: ['frame.project.list'], topics: ['project.changed'] },
  useSessions: { calls: ['frame.session.list'], topics: ['session.changed'] },
  useJournal: { calls: ['frame.journal.read'], topics: ['journal.<session>'] },
};

function files(dir) {
  const out = [];
  if (!fs.existsSync(dir)) return out;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...files(full));
    else if (/\.(tsx?|css)$/.test(entry.name)) out.push(full);
  }
  return out;
}

const uniq = (list) => [...new Set(list)].sort();
const all = (text, re) => [...text.matchAll(re)].map((m) => m[1]);

function contract(pkg) {
  const source = files(path.join(pkg.dir, 'src')).filter((f) => !f.endsWith('.css')).map((f) => fs.readFileSync(f, 'utf8')).join('\n');
  const reads = uniq([...all(source, /useShared<[^(\n]*>\(\s*'([^']+)'/g), ...all(source, /useShared\(\s*'([^']+)'/g), ...all(source, /getShared(?:<[^>]*>)?\(\s*'([^']+)'/g)]);
  const writes = uniq([...all(source, /setShared\(\s*'([^']+)'/g), ...all(source, /\[\s*\w*\s*,\s*set\w+\s*\]\s*=\s*useShared(?:<[^(\n]*>)?\(\s*'([^']+)'/g)]);
  const own = uniq([...all(source, /useSlotState<[^(\n]*>\(\s*'([^']+)'/g), ...all(source, /useSlotState\(\s*'([^']+)'/g)]);
  const hosts = uniq([...all(source, /host\.Slots?\s+name="([^"]+)"/g), ...all(source, /<host\.Slots?[^>]*name=\{?'([^']+)'/g)]);
  const calls = uniq(all(source, /\.call(?:<[^>]*>)?\(\s*'([a-z_]+\.[a-z_.]+)'/g).concat(all(source, /(?:run|act|swap)\(\s*'([a-z_]+\.[a-z_.]+)'/g)));
  const topics = uniq([...all(source, /topics:\s*\[([^\]]*)\]/g).flatMap((list) => all(list, /'([^']+)'/g)), ...all(source, /useEvent\(\s*'([^']+)'/g), ...all(source, /\.on\(\s*'([^']+)'/g)]);
  for (const [helper, use] of Object.entries(HELPERS)) {
    if (!new RegExp(`\\b${helper}\\(`).test(source)) continue;
    reads.push(...(use.reads ?? []));
    // A hook's writes count when the plugin takes its setter (`[x, setX] = useCodeScope()`,
    // `{ setTarget } = useCodeTarget()`); plain functions (openInCode, openTarget) always write.
    const takesSetter = new RegExp(`(\\[\\s*\\w*\\s*,\\s*set\\w+\\s*\\]|\\{[^}]*\\bset\\w+[^}]*\\})\\s*=\\s*${helper}\\(`).test(source);
    if (!helper.startsWith('use') || takesSetter || (helper === 'useSelection' && /\bselect(Project|Session)?\(|setSessionId|setProjectId/.test(source))) writes.push(...(use.writes ?? []));
    calls.push(...(use.calls ?? []));
    topics.push(...(use.topics ?? []));
  }
  const props = PROPS[pkg.slot] ?? (pkg.slot.startsWith('pane.') ? PROPS['pane.*@1'] : 'none besides `slot`');
  const list = (items) => (items.length ? items.map((i) => `\`${i}\``).join(', ') : 'none');
  return [
    START,
    '## Slot contract',
    '',
    `- **Fills:** \`${pkg.slot}\` as \`${pkg.id}\`${pkg.slot === 'theme@1' ? ' (exactly one theme is active)' : ''}`,
    `- **Props:** ${props}`,
    `- **Hosts:** ${[hosts.length ? list(hosts) : '', DISCOVERS[pkg.id] ?? DISCOVERS[pkg.slot] ?? ''].filter(Boolean).join('; ') || 'no slots'}`,
    `- **Workbench state read:** ${list(uniq(reads))}`,
    `- **Workbench state written:** ${list(uniq(writes))}`,
    `- **Own durable state (survives hot swaps):** ${list(own)}`,
    `- **Frame methods called:** ${list(uniq(calls))}`,
    `- **Topics followed:** ${list(uniq(topics))}`,
    '',
    'Styles use the theme\'s tokens and primitives only (`ui/verify/tokens.mjs` checks). Nothing is',
    'imported from the renderer or from another plugin: the package builds alone (`ui/verify/standalone.mjs`).',
    END,
  ].join('\n');
}

const check = process.argv.includes('--check');
const stale = [];
for (const pkg of uiPackages()) {
  const readme = path.join(pkg.dir, 'README.md');
  // Packages documented by their plugin's own README (a single-package plugin) carry no section.
  if (!fs.existsSync(readme)) continue;
  const text = fs.readFileSync(readme, 'utf8');
  const section = contract(pkg);
  const next = text.includes(START)
    ? text.slice(0, text.indexOf(START)) + section + text.slice(text.indexOf(END) + END.length)
    : `${text.trimEnd()}\n\n${section}\n`;
  if (next === text) continue;
  if (check) stale.push(path.relative(process.cwd(), readme));
  else fs.writeFileSync(readme, next);
}
if (check && stale.length) {
  console.error(`README slot contracts out of date (run node scripts/readme-contracts.mjs):\n  ${stale.join('\n  ')}`);
  process.exit(1);
}
